import {chromium} from 'playwright';
import {Temporal} from '@js-temporal/polyfill';
import {randomUUID} from 'node:crypto';
import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
import {db} from '../lib/db';

const target = new URL(process.env.DATABASE_URL || 'postgresql://invalid');
if (target.hostname !== '127.0.0.1' || target.port !== '56441') throw Error('Use the isolated QA database.');
const base = 'http://127.0.0.1:3003', folder = 'artifacts/qa-20261121/round1';
const today = Temporal.Now.plainDateISO('Pacific/Auckland');
const date = today.add({days: ((1-today.dayOfWeek+7)%7)||7}).toString();
const email = `back-${randomUUID().slice(0,8)}@example.test`;
await mkdir(folder,{recursive:true});
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_PATH||'C:/Program Files/Google/Chrome/Application/chrome.exe'});
const page=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
page.setDefaultTimeout(30000);
const checks:Record<string,unknown>={date}; let stage='guest selection';
try {
  await page.goto(base+'/book/qa-rimu'); await page.waitForLoadState('networkidle');
  await page.getByRole('button',{name:/Kids cut/}).click();
  await page.locator('.mobile-service-bar').getByRole('button',{name:'Continue'}).click();
  await page.getByLabel('Choose your barber').selectOption('qa-ari');
  await page.getByLabel('Booking date').fill(date);
  await page.getByRole('button',{name:'9:00 am',exact:true}).click();
  await page.getByRole('button',{name:'Continue',exact:true}).click();
  await page.getByLabel('Your name').fill('Browser Back QA');
  await page.getByLabel('Email for confirmation').fill(email);
  stage='guest browser Back and Forward';
  await page.goBack(); await page.getByRole('heading',{name:'Find your time'}).waitFor();
  assert.equal(await page.getByLabel('Choose your barber').inputValue(),'qa-ari');
  assert.equal(await page.getByLabel('Booking date').inputValue(),date);
  assert.equal(await page.getByRole('button',{name:'9:00 am',exact:true}).getAttribute('aria-pressed'),'true');
  await page.goForward(); await page.getByRole('heading',{name:'Your details'}).waitFor();
  assert.equal(await page.getByLabel('Your name').inputValue(),'Browser Back QA');
  assert.equal(await page.getByLabel('Email for confirmation').inputValue(),email);
  checks.guest='Barber, date, time, name and email survive Back and Forward.';
  stage='guest confirmation and duplicate prevention';
  await page.getByRole('button',{name:'Confirm booking'}).click();
  await page.getByRole('heading',{name:'You’re booked in.'}).waitFor();
  const link=await page.getByLabel('Your private link').inputValue();
  await page.goBack(); await page.getByRole('heading',{name:'You’re booked in.'}).waitFor();
  const found=await db.query('SELECT e.id FROM schedule_entries e JOIN guest_booking_links g ON g.entry_id=e.id WHERE g.email=$1',[email]);
  assert.equal(found.rowCount,1,'Back after confirmation must not create another appointment');
  checks.confirmed='Browser Back retains the confirmation and exactly one appointment.';
  await page.goto(link); page.once('dialog',d=>d.accept());
  await page.getByRole('button',{name:'Cancel booking'}).click(); await page.getByText('cancelled',{exact:true}).waitFor();
  stage='whānau browser Back and Forward';
  await page.goto(base+'/whanau/qa-rimu');await page.waitForLoadState('networkidle');
  await page.getByLabel('First name for person 1').fill('Luca Back');
  await page.getByLabel('Service for person 1').selectOption('qa-kids');
  await page.getByLabel('First name for person 2').fill('Mia Back');
  await page.getByLabel('Service for person 2').selectOption('qa-kids');
  await page.getByRole('button',{name:'Find times'}).click();
  await page.getByLabel('Visit date').fill(date);
  const different=page.getByRole('button',{name:/At the same time, with different barbers/});
  await different.waitFor({state:'visible'});
  await page.waitForFunction(()=>[...document.querySelectorAll<HTMLButtonElement>('.visit-types button')].every(b=>!b.disabled));
  await different.click();await page.getByRole('button',{name:'9:00 am',exact:true}).click();
  await page.getByRole('button',{name:'Continue',exact:true}).click();
  await page.getByLabel('Organiser’s email').fill(email);
  await page.getByLabel('Organiser’s mobile').fill('not a phone');
  await page.getByLabel('Organiser’s mobile').press('Tab');
  await page.getByRole('alert').getByText('Please enter a valid organiser mobile number.',{exact:false}).waitFor();
  assert.equal(await page.getByLabel('Organiser’s mobile').getAttribute('aria-invalid'),'true');
  assert.equal(await page.getByLabel('Organiser’s mobile').evaluate((el:HTMLInputElement)=>el.validity.valid),false);
  assert.ok(await page.getByRole('button',{name:'Confirm visit'}).isDisabled());
  assert.equal(await page.getByLabel('Organiser’s email').inputValue(),email);
  await page.getByLabel('Organiser’s mobile').fill('021 555 0123');
  await page.route('**/api/visit',async route=>{if(route.request().postDataJSON()?.action==='create')await route.abort('failed');else await route.continue()});
  await page.getByRole('button',{name:'Confirm visit'}).click();
  await page.getByRole('alert').getByText('We couldn’t confirm whether your visit was saved.',{exact:false}).waitFor();
  assert.equal(await page.getByLabel('Organiser’s mobile').inputValue(),'021 555 0123');
  assert.ok(await page.getByRole('button',{name:'Confirm visit'}).isDisabled());
  await page.unrouteAll({behavior:'wait'});
  await page.goBack(); await page.getByRole('heading',{name:'Choose a time together'}).waitFor();
  assert.equal(await different.getAttribute('aria-pressed'),'true');
  assert.equal(await page.getByRole('button',{name:'9:00 am',exact:true}).getAttribute('aria-pressed'),'true');
  assert.match(await page.locator('.visit-plan').innerText(),/At the same time, with different barbers/);
  await page.goForward();await page.getByRole('heading',{name:'Confirm your visit'}).waitFor();
  assert.equal(await page.getByLabel('Organiser’s email').inputValue(),email);
  assert.equal(await page.getByLabel('Organiser’s mobile').inputValue(),'021 555 0123');
  assert.match(await page.locator('.visit-summary').innerText(),/Luca Back[\s\S]*Mia Back/);
  await page.screenshot({path:folder+'/whanau-browser-forward-phone.png',fullPage:true});
  checks.whanau='People, arrangement, date, time and organiser contact survive validation, an interrupted request, Back and Forward.';
  console.log('PASS: guest and whānau browser Back/Forward preserve choices, details and the single confirmation.');
} catch (error) {
  checks.failure={stage,message:error instanceof Error?error.message:String(error)};
  console.error('Browser history check failed at:',stage);
  await page.screenshot({path:folder+'/browser-back-failure.png',fullPage:true}).catch(()=>{});
  throw error;
} finally {
  await writeFile(folder+'/browser-history.json',JSON.stringify(checks,null,2));
  await browser.close();await db.end();
}
